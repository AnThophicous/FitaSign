Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
$output = Join-Path $root 'build'
New-Item -ItemType Directory -Path $output -Force | Out-Null
$bitmap = [System.Drawing.Bitmap]::new(512, 512)
$graphics = [System.Drawing.Graphics]::FromImage($bitmap)
$graphics.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
$graphics.Clear([System.Drawing.Color]::Transparent)
$background = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#252525'))
$foreground = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#d4d4d4'))
$path = [System.Drawing.Drawing2D.GraphicsPath]::new()
$path.AddArc(8, 8, 144, 144, 180, 90)
$path.AddArc(360, 8, 144, 144, 270, 90)
$path.AddArc(360, 360, 144, 144, 0, 90)
$path.AddArc(8, 360, 144, 144, 90, 90)
$path.CloseFigure()
$graphics.FillPath($background, $path)
$graphics.FillRectangle($foreground, 148, 124, 60, 266)
$graphics.FillRectangle($foreground, 148, 124, 216, 58)
$graphics.FillRectangle($foreground, 148, 238, 168, 56)
$bitmap.Save((Join-Path $output 'icon.png'), [System.Drawing.Imaging.ImageFormat]::Png)
$small = [System.Drawing.Bitmap]::new(256, 256)
$smallGraphics = [System.Drawing.Graphics]::FromImage($small)
$smallGraphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
$smallGraphics.DrawImage($bitmap, 0, 0, 256, 256)
$memory = [System.IO.MemoryStream]::new()
$small.Save($memory, [System.Drawing.Imaging.ImageFormat]::Png)
$data = $memory.ToArray()
$stream = [System.IO.File]::Create((Join-Path $output 'icon.ico'))
$writer = [System.IO.BinaryWriter]::new($stream)
$writer.Write([uint16]0)
$writer.Write([uint16]1)
$writer.Write([uint16]1)
$writer.Write([byte]0)
$writer.Write([byte]0)
$writer.Write([byte]0)
$writer.Write([byte]0)
$writer.Write([uint16]1)
$writer.Write([uint16]32)
$writer.Write([uint32]$data.Length)
$writer.Write([uint32]22)
$writer.Write($data)
$writer.Dispose()
$memory.Dispose()
$smallGraphics.Dispose()
$small.Dispose()
$path.Dispose()
$foreground.Dispose()
$background.Dispose()
$graphics.Dispose()
$bitmap.Dispose()
